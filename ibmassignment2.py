print("Dataset loaded successfully!")
print("Dataset Shape:", df.shape)

display(df.head())

"""**Inspect the dataset**"""

print("Dataset Information:")
df.info()

print("\nColumn Names:")
print(df.columns.tolist())

print("\nStatistical Summary:")
display(df.describe(include='all').T)

"""**Check missing values**"""

missing_values = df.isnull().sum()

missing_report = pd.DataFrame({
    'Column': df.columns,
    'Missing Values': missing_values.values,
    'Missing Percentage':
        (missing_values.values / len(df)) * 100
})

display(missing_report)

print("Total Missing Values:", df.isnull().sum().sum())

"""**Handle missing values**"""

df_clean = df.copy()

numeric_columns = df_clean.select_dtypes(
    include=np.number
).columns

categorical_columns = df_clean.select_dtypes(
    include='object'
).columns

# Fill numerical missing values with median
for col in numeric_columns:
    df_clean[col] = df_clean[col].fillna(
        df_clean[col].median()
    )

# Fill categorical missing values with mode
for col in categorical_columns:
    if df_clean[col].isnull().any():
        df_clean[col] = df_clean[col].fillna(
            df_clean[col].mode()[0]
        )

print("Missing values handled successfully!")
print("Remaining Missing Values:",
      df_clean.isnull().sum().sum())

"""**Handle duplicate records**"""

duplicates = df_clean.duplicated().sum()

print("Duplicate Records Found:", duplicates)

df_clean = df_clean.drop_duplicates()

print("Dataset Shape After Removing Duplicates:",
      df_clean.shape)

print("Remaining Duplicates:",
      df_clean.duplicated().sum())

"""**Detect outliers**"""

numeric_columns = df_clean.select_dtypes(
    include=np.number
).columns.tolist()

# Exclude identifier and constant columns
exclude_columns = [
    'EmployeeNumber',
    'EmployeeCount',
    'Over18',
    'StandardHours'
]

numeric_columns = [
    col for col in numeric_columns
    if col not in exclude_columns
]

outlier_results = []

for col in numeric_columns:

    Q1 = df_clean[col].quantile(0.25)
    Q3 = df_clean[col].quantile(0.75)

    IQR = Q3 - Q1

    lower_bound = Q1 - 1.5 * IQR
    upper_bound = Q3 + 1.5 * IQR

    outliers = (
        (df_clean[col] < lower_bound) |
        (df_clean[col] > upper_bound)
    ).sum()

    outlier_results.append({
        'Feature': col,
        'Lower Bound': lower_bound,
        'Upper Bound': upper_bound,
        'Outlier Count': outliers
    })

outlier_report = pd.DataFrame(outlier_results)

display(outlier_report)

"""**Visualize outliers**"""

plt.figure(figsize=(16, 10))

for i, col in enumerate(numeric_columns[:12]):
    plt.subplot(3, 4, i + 1)
    sns.boxplot(y=df_clean[col])
    plt.title(col)
    plt.tight_layout()

plt.show()

"""**Create derived HR features**"""

df_engineered = df_clean.copy()

# 1. Total Employee Satisfaction
satisfaction_columns = [
    'EnvironmentSatisfaction',
    'JobSatisfaction',
    'RelationshipSatisfaction',
    'WorkLifeBalance'
]

df_engineered['TotalSatisfaction'] = (
    df_engineered[satisfaction_columns].sum(axis=1)
)

# 2. Employee Tenure Ratio
df_engineered['TenureRatio'] = np.where(
    df_engineered['TotalWorkingYears'] > 0,
    df_engineered['YearsAtCompany'] /
    df_engineered['TotalWorkingYears'],
    0
)

# 3. Career Start Age
df_engineered['CareerStartAge'] = (
    df_engineered['Age'] -
    df_engineered['TotalWorkingYears']
)

print("New HR Features Created Successfully!")

display(
    df_engineered[
        [
            'TotalSatisfaction',
            'TenureRatio',
            'CareerStartAge'
        ]
    ].head()
)


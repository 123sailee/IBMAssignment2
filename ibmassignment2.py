display(df_engineered.head())

"""**Separate numerical and categorical variables**"""

# Separate target variable
X = df_engineered.drop(columns=['Attrition'])
y = df_engineered['Attrition'].map({
    'Yes': 1,
    'No': 0
})

# Remove identifier and constant columns
columns_to_drop = [
    'EmployeeNumber',
    'EmployeeCount',
    'Over18',
    'StandardHours'
]

X = X.drop(
    columns=columns_to_drop,
    errors='ignore'
)

# Identify numerical and categorical columns
numerical_features = X.select_dtypes(
    include=np.number
).columns.tolist()

categorical_features = X.select_dtypes(
    include=['object', 'category']
).columns.tolist()

print("Numerical Features:", len(numerical_features))
print("Categorical Features:", len(categorical_features))

print("\nNumerical Columns:")
print(numerical_features)

print("\nCategorical Columns:")
print(categorical_features)

print("\nTarget Variable Distribution:")
print(y.value_counts())

"""**Encode categorical variables and scale numerical variables**"""

from sklearn.preprocessing import StandardScaler, OneHotEncoder
from sklearn.impute import SimpleImputer
from sklearn.pipeline import Pipeline
from sklearn.compose import ColumnTransformer

# Numerical preprocessing
numerical_pipeline = Pipeline(steps=[
    ('imputer', SimpleImputer(strategy='median')),
    ('scaler', StandardScaler())
])

# Categorical preprocessing
categorical_pipeline = Pipeline(steps=[
    ('imputer', SimpleImputer(strategy='most_frequent')),
    ('encoder', OneHotEncoder(handle_unknown='ignore'))
])

# Combine both pipelines
preprocessor = ColumnTransformer(
    transformers=[
        ('num', numerical_pipeline, numerical_features),
        ('cat', categorical_pipeline, categorical_features)
    ]
)

print("Numerical and categorical preprocessing configured!")

"""**Create the complete preprocessing pipeline**"""

# Create complete preprocessing pipeline
preprocessing_pipeline = Pipeline(steps=[
    ('preprocessor', preprocessor)
])

# Fit and transform the dataset
X_processed = preprocessing_pipeline.fit_transform(X)

# Convert sparse matrix to dense array if necessary
if hasattr(X_processed, 'toarray'):
    X_processed = X_processed.toarray()

# Get transformed feature names
feature_names = (
    preprocessing_pipeline
    .named_steps['preprocessor']
    .get_feature_names_out()
)

# Create processed DataFrame
processed_df = pd.DataFrame(
    X_processed,
    columns=feature_names,
    index=X.index
)

# Add target variable
processed_df['Attrition'] = y

print("Preprocessing Pipeline Executed Successfully!")

print("Original Features:", X.shape[1])
print("Processed Features:", processed_df.shape[1] - 1)

display(processed_df.head())

"""**Export processed data and reports**"""

